export class I18n {
  static currentLanguage = 'en';

  static init(lang = 'en') {
    const saved = localStorage.getItem('medipass_language_pref');
    this.currentLanguage = saved || lang || 'en';
  }

  static setLanguage(lang) {
    if (translations[lang]) {
      this.currentLanguage = lang;
      localStorage.setItem('medipass_language_pref', lang);
      window.dispatchEvent(new CustomEvent('languagechanged', { detail: { language: lang } }));
    }
  }

  static t(key) {
    const langDict = translations[this.currentLanguage] || translations.en;
    return langDict[key] || translations.en[key] || key;
  }
}

I18n.init();
export default I18n;
